import { Head, Link } from '@inertiajs/react';
import AppLayout from '../../Layouts/AppLayout';
import PageAlerts from '../../Components/Exams/PageAlerts';
import { dateLabel, humanize, useMoney } from '../../lib/fees';

export default function PaymentsShow({ receipt, isPortal }) {
    const money = useMoney();

    return (
        <AppLayout title={`Receipt ${receipt.receiptNumber}`} description={`${receipt.studentName} · ${receipt.admissionNumber}`}>
            <Head title={`Receipt ${receipt.receiptNumber}`} />
            <div className="print:hidden">
                <PageAlerts />
                <div className="mb-5 flex flex-wrap items-center justify-between gap-3">
                    <Link href={isPortal ? '/fees' : `/invoices/${receipt.invoiceId}`} className="rounded-xl border border-slate-200 bg-white px-4 py-2.5 text-sm font-semibold text-slate-700 hover:bg-slate-50">
                        {isPortal ? 'Back to my fees' : 'Back to invoice'}
                    </Link>
                    <button type="button" onClick={() => window.print()} className="rounded-xl bg-teal-700 px-4 py-2.5 text-sm font-semibold text-white hover:bg-teal-800">Print / Save as PDF</button>
                </div>
            </div>

            <article className="mx-auto max-w-2xl border border-slate-300 bg-white p-8 sm:p-10 print:max-w-none print:border-0 print:p-8">
                <p className="text-center text-xs font-semibold uppercase tracking-[0.25em] text-teal-800">Payment receipt</p>
                <h1 className="mt-3 text-center text-2xl font-bold tracking-tight text-slate-950">{receipt.schoolName}</h1>
                <div className="my-6 h-px bg-slate-200" />

                <dl className="grid gap-4 text-sm sm:grid-cols-2">
                    <Row label="Receipt number" value={receipt.receiptNumber} />
                    <Row label="Date" value={dateLabel(receipt.date)} />
                    <Row label="Student" value={receipt.studentName} />
                    <Row label="Admission number" value={receipt.admissionNumber} />
                    <Row label="Invoice" value={receipt.invoiceNumber} />
                    <Row label="Academic year" value={receipt.academicYear} />
                    <Row label="Payment method" value={humanize(receipt.method)} capitalize />
                    <Row label="Transaction reference" value={receipt.reference} />
                    {receipt.notes && <div className="sm:col-span-2"><Row label="Notes" value={receipt.notes} /></div>}
                </dl>

                <div className="mt-8 rounded-xl bg-slate-50 px-5 py-4 text-center">
                    <p className="text-xs font-medium text-slate-500">Amount received</p>
                    <p className="mt-1 text-3xl font-bold tracking-tight text-slate-950">{money(receipt.amount)}</p>
                </div>

                <dl className="mt-6 grid gap-3 border-t border-slate-200 pt-4 text-sm sm:grid-cols-3">
                    <Row label="Invoice total" value={money(receipt.invoiceTotal)} />
                    <Row label="Total paid to date" value={money(receipt.invoicePaid)} />
                    <Row label="Balance outstanding" value={money(receipt.invoiceOutstanding)} />
                </dl>
                <p className="mt-6 text-center text-xs text-slate-500">This receipt was generated by the school's fee system and shows the invoice position today.</p>
            </article>
        </AppLayout>
    );
}

function Row({ label, value, capitalize = false }) {
    return (
        <div>
            <dt className="text-xs font-medium text-slate-500">{label}</dt>
            <dd className={`mt-1 text-slate-900 ${capitalize ? 'capitalize' : ''}`}>{value || '—'}</dd>
        </div>
    );
}