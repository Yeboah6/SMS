<?php

namespace App\Services;

use App\Models\Staff;
use App\Models\User;
use Illuminate\Database\QueryException;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Arr;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Validation\ValidationException;

class StaffDirectoryService
{
    public const LINKABLE_ROLES = [
        'Teacher',
        'Principal',
        'Accountant',
        'Librarian',
        'Receptionist',
    ];

    public const TEACHER_ROLE = 'Teacher';

    /** Columns copied straight onto the staff row. */
    private const PROFILE_FIELDS = [
        'department_id',
        'designation_id',
        'name',
        'email',
        'phone',
        'joining_date',
        'qualifications',
        'status',
    ];

    /** The staff role held by an account (loaded roles), or null. */
    public static function roleOf(?User $user): ?string
    {
        return $user?->roles
            ->pluck('name')
            ->first(fn (string $name): bool => in_array($name, self::LINKABLE_ROLES, true));
    }

    /**
     * Creates the sign-in account, assigns the role and creates the staff profile
     * with the next staff number (generated by Staff::nextNumber(), e.g. ST001).
     *
     * @param  array<string, mixed>  $data  role, password and the profile fields
     */
    public function create(array $data): Staff
    {
        // staff_number is unique; if two requests race for the same number, retry with the next one.
        for ($attempt = 1; ; $attempt++) {
            try {
                return DB::transaction(fn (): Staff => $this->createProfile($data));
            } catch (UniqueConstraintViolationException $exception) {
                if ($attempt >= 3) {
                    throw $exception;
                }
            }
        }
    }

    /**
     * @param  array<string, mixed>  $data  role, optional password and the profile fields
     */
    public function update(Staff $staff, array $data): Staff
    {
        return DB::transaction(function () use ($staff, $data): Staff {
            $staff = Staff::query()->lockForUpdate()->findOrFail($staff->getKey());
            $role = $data['role'];
            $isTeacher = $role === self::TEACHER_ROLE;

            if (! $isTeacher && (
                $staff->classAssignments()->exists()
                || $staff->subjectAssignments()->exists()
            )) {
                throw ValidationException::withMessages([
                    'role' => 'A teacher with academic assignments cannot be changed to a non-teaching role.',
                ]);
            }

            $user = $staff->user_id ? User::query()->lockForUpdate()->find($staff->user_id) : null;

            if ($user) {
                $this->ensureOnlyStaffRoles($user);
                $user->forceFill(['name' => $data['name'], 'email' => $data['email']]);
                if (! empty($data['password'])) {
                    $user->forceFill(['password' => Hash::make($data['password'])]);
                }
                $user->save();
                $this->setStaffRole($user, $role);
            } else {
                $user = $this->createAccount($data);
            }

            $staff->update([
                ...Arr::only($data, self::PROFILE_FIELDS),
                'user_id' => $user->id,
                'is_teacher' => $isTeacher,
            ]);

            return $staff->refresh();
        });
    }

    /** Deletes the profile and the sign-in account that was created for it. */
    public function delete(Staff $staff): void
    {
        DB::transaction(function () use ($staff): void {
            $staff = Staff::query()->lockForUpdate()->findOrFail($staff->getKey());

            if ($staff->classAssignments()->exists() || $staff->subjectAssignments()->exists()) {
                throw ValidationException::withMessages([
                    'staff' => 'This staff member has academic teaching assignments and cannot be deleted.',
                ]);
            }

            $user = $staff->user()->with('roles:id,name')->first();
            $staff->delete();

            // Only staff-only accounts are removed; an account with other roles is left untouched.
            if ($user && $user->roles->pluck('name')->diff(self::LINKABLE_ROLES)->isEmpty()) {
                try {
                    // Users are soft-deleted but their email stays unique, so free it for reuse.
                    // The original email is kept on the (soft-deleted) staff row.
                    $user->forceFill(['email' => 'removed-'.$user->id.'@deleted.invalid'])->save();
                    $user->delete();
                } catch (QueryException) {
                    throw ValidationException::withMessages([
                        'staff' => 'The sign-in account has linked records and cannot be removed. Remove it in User Administration first.',
                    ]);
                }
            }
        });
    }

    private function createProfile(array $data): Staff
    {
        $user = $this->createAccount($data);

        return Staff::query()->create([
            ...Arr::only($data, self::PROFILE_FIELDS),
            'user_id' => $user->id,
            'is_teacher' => $data['role'] === self::TEACHER_ROLE,
        ]);
    }

    private function createAccount(array $data): User
    {
        $user = new User;
        $user->forceFill([
            'name' => $data['name'],
            'email' => $data['email'],
            'password' => Hash::make($data['password']),
            // Provisioned by an administrator, so no verification email is needed.
            'email_verified_at' => now(),
        ])->save();

        $user->assignRole($data['role']);

        return $user;
    }

    /** Swaps the account's staff role without touching any other role. */
    private function setStaffRole(User $user, string $role): void
    {
        foreach (self::LINKABLE_ROLES as $other) {
            if ($other !== $role && $user->hasRole($other)) {
                $user->removeRole($other);
            }
        }

        if (! $user->hasRole($role)) {
            $user->assignRole($role);
        }
    }

    /** Accounts that also hold other roles (such as Super Admin) are managed in User Administration. */
    private function ensureOnlyStaffRoles(User $user): void
    {
        if ($user->roles->pluck('name')->diff(self::LINKABLE_ROLES)->isNotEmpty()) {
            throw ValidationException::withMessages([
                'role' => 'This account has additional roles. Manage its roles in User Administration.',
            ]);
        }
    }
}